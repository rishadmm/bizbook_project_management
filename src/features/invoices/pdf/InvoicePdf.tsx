import { Document, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import { fromGross } from "../calc";
import type { InvoiceDetail } from "../queries";
import { amountInWords } from "../words";
import { pdfFontFamily } from "./fonts";

const PRIMARY = "#635BFF", DARK = "#0F172A", MUTED = "#6B7280", LINE = "#E5E7EB", SOFT = "#EEF2FF";
const num = (v: number, d = 2) => v.toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d });
const qty = (v: number) => v.toLocaleString("en-US", { maximumFractionDigits: 3 });
const date = (iso: string | null | undefined) => {
  const m = iso ? /^(\d{4})-(\d{2})-(\d{2})/.exec(iso) : null;
  return m ? `${m[3]} ${["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"][Number(m[2]) - 1]} ${m[1]}` : "—";
};

const WATERMARK: Record<string, { text: string; color: string } | undefined> = {
  submitted: { text: "DRAFT", color: "#94A3B8" }, under_review: { text: "UNDER REVIEW", color: "#F59E0B" }, rejected: { text: "REJECTED", color: "#EF4444" },
};

function styles(font: string) {
  return StyleSheet.create({
    page: { fontFamily: font, fontSize: 8.5, color: "#1F2937", paddingTop: 34, paddingBottom: 52, paddingHorizontal: 34 },
    accent: { height: 5, backgroundColor: PRIMARY, borderRadius: 3, marginBottom: 12 },
    head: { flexDirection: "row", justifyContent: "space-between", alignItems: "flex-start", marginBottom: 14 },
    mark: { width: 30, height: 30, borderRadius: 7, backgroundColor: PRIMARY, alignItems: "center", justifyContent: "center", marginRight: 9 },
    markText: { color: "#fff", fontSize: 12, fontWeight: 800 },
    company: { fontSize: 13, fontWeight: 800, color: DARK },
    title: { fontSize: 12.5, fontWeight: 800, color: PRIMARY, textAlign: "right" },
    h: { fontSize: 9.5, fontWeight: 800, color: DARK, marginBottom: 5 },
    label: { fontSize: 6.8, fontWeight: 700, color: MUTED, textTransform: "uppercase", letterSpacing: 0.6, marginBottom: 2 },
    cols: { flexDirection: "row", gap: 12, marginBottom: 10 },
    box: { flex: 1, borderWidth: 1, borderColor: LINE, borderRadius: 6, padding: 8 },
    bold: { fontWeight: 700, color: DARK },
    grid: { flexDirection: "row", flexWrap: "wrap", borderWidth: 1, borderColor: LINE, borderRadius: 6, marginBottom: 12 },
    cell: { width: "25%", padding: 6, borderRightWidth: 0 },
    th: { flexDirection: "row", backgroundColor: DARK, color: "#fff", paddingVertical: 4, paddingHorizontal: 3 },
    thText: { color: "#fff", fontSize: 6.8, fontWeight: 700, textTransform: "uppercase" },
    tr: { flexDirection: "row", paddingVertical: 3.5, paddingHorizontal: 3, fontSize: 7.5 },
    right: { textAlign: "right" },
    totals: { alignSelf: "flex-end", width: 250, borderWidth: 1, borderColor: LINE, borderRadius: 6, padding: 8, marginTop: 10 },
    trow: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 1.5 },
    net: { flexDirection: "row", justifyContent: "space-between", backgroundColor: PRIMARY, color: "#fff", borderRadius: 5, paddingVertical: 5, paddingHorizontal: 7, marginTop: 4 },
    sig: { flex: 1, borderWidth: 1, borderColor: LINE, borderRadius: 6, padding: 7, height: 62 },
    footer: { position: "absolute", bottom: 20, left: 34, right: 34, flexDirection: "row", justifyContent: "space-between", fontSize: 7, color: MUTED, borderTopWidth: 1, borderTopColor: LINE, paddingTop: 5 },
  });
}

/** Subcontractor invoice / payment certificate as an A4 PDF (BizBook look). Multi-page safe: repeating table header, no-split rows, footer with page numbers. */
export function InvoicePdf({ d, generatedAt }: { d: InvoiceDetail; generatedAt: string }) {
  const font = pdfFontFamily();
  const S = styles(font);
  const i = d.invoice, cur = i.currency || "AED";
  const wm = WATERMARK[i.status];
  const cert = fromGross(d.certifiedState ? i.certified_amount : 0, i.vat_rate);
  const W = { n: "4%", d: "28%", u: "6%", c: "10%", p: "10%", t: "10%", cu: "10%", r: "10%", a: "12%" };
  const remarks = d.lines.filter((l) => l.remarks);
  const Kv = ({ k, v }: { k: string; v: string }) => <View style={S.cell}><Text style={S.label}>{k}</Text><Text style={S.bold}>{v}</Text></View>;
  return (
    <Document title={`${i.invoice_no ?? i.id} - Subcontractor invoice`} author="BizBook Project" subject="Subcontractor Invoice — Payment Certificate">
      <Page size="A4" style={S.page}>
        <Text fixed style={{ textAlign: "center", position: "absolute", bottom: 22, left: 34, right: 34, fontSize: 7, color: MUTED }} render={({ pageNumber, totalPages }) => `Generated by BizBook Project - ${generatedAt} - Page ${pageNumber} of ${totalPages}`} />
        {wm && (
          <View fixed style={{ position: "absolute", top: 300, left: 0, right: 0, alignItems: "center" }}>
            <Text style={{ fontSize: 64, fontWeight: 800, color: wm.color, opacity: 0.16, transform: "rotate(-30deg)" }}>{wm.text}</Text>
          </View>
        )}
        <View>
        <View style={S.accent} />
        <View style={S.head}>
          <View style={{ flexDirection: "row", alignItems: "center" }}>
            <View style={S.mark}><Text style={S.markText}>BB</Text></View>
            <View style={{ maxWidth: 270 }}><Text style={S.company}>{d.company.name}</Text><Text style={{ color: MUTED, fontSize: 7.5, marginTop: 4 }}>{d.company.address}</Text></View>
          </View>
          <View style={{ maxWidth: 230, marginLeft: 16 }}><Text style={S.title}>Subcontractor Invoice</Text><Text style={[S.title, { color: DARK, fontSize: 9.5 }]}>Payment Certificate</Text><Text style={{ textAlign: "right", color: MUTED, marginTop: 2 }}>{i.invoice_no ?? `#${i.id}`}</Text></View>
        </View>

        <View style={S.cols}>
          <View style={S.box}>
            <Text style={S.label}>Subcontractor</Text>
            <Text style={[S.bold, { fontSize: 10 }]}>{d.subcontractor.name}</Text>
            {d.subcontractor.address && <Text>{d.subcontractor.address}</Text>}
            <Text>TRN {d.subcontractor.tax_no ?? "—"}{d.subcontractor.trade_license_no ? `  ·  Licence ${d.subcontractor.trade_license_no}` : ""}</Text>
            <Text style={{ color: MUTED }}>{[d.subcontractor.contact_person, d.subcontractor.phone, d.subcontractor.email].filter(Boolean).join("  ·  ")}</Text>
            {d.subcontractor.bank_name && <Text style={{ color: MUTED }}>{d.subcontractor.bank_name}{d.subcontractor.iban_masked ? `  ·  IBAN ${d.subcontractor.iban_masked}` : ""}</Text>}
          </View>
          <View style={S.box}>
            <Text style={S.label}>Bill to</Text>
            <Text style={[S.bold, { fontSize: 10 }]}>{d.company.name}</Text>
            {d.company.address && <Text>{d.company.address}</Text>}
            <Text>TRN {d.company.trn || "—"}</Text>
            {d.client && <Text style={{ color: MUTED }}>Client: {d.client.name}</Text>}
          </View>
        </View>

        <View style={S.grid}>
          <Kv k="Invoice no." v={i.invoice_no ?? `#${i.id}`} /><Kv k="Supplier ref." v={i.sub_invoice_ref ?? "—"} /><Kv k="Invoice date" v={date(i.invoice_date)} /><Kv k="Period" v={i.period_from ? `${date(i.period_from)} – ${date(i.period_to)}` : "—"} />
          <Kv k="Due date" v={date(i.due_date)} /><Kv k="Project" v={`${d.project.code}`} /><Kv k="Subcontract" v={d.assignment.code ?? "—"} /><Kv k="Stage" v={d.stages.map((s) => s.code ?? s.name).join(", ") || "—"} />
        </View>

        <Text style={S.h}>Invoice lines</Text>
        <View>
        <View fixed style={S.th}>
          <Text style={[S.thText, { width: W.n }]}>#</Text><Text style={[S.thText, { width: W.d }]}>Description</Text><Text style={[S.thText, { width: W.u }]}>Unit</Text>
          <Text style={[S.thText, S.right, { width: W.c }]}>Contract</Text><Text style={[S.thText, S.right, { width: W.p }]}>Previous</Text><Text style={[S.thText, S.right, { width: W.t }]}>This period</Text>
          <Text style={[S.thText, S.right, { width: W.cu }]}>Cumulative</Text><Text style={[S.thText, S.right, { width: W.r }]}>Rate</Text><Text style={[S.thText, S.right, { width: W.a }]}>Amount</Text>
        </View>
        {d.lines.map((l, k) => (
          <View key={l.id} wrap={false} style={[S.tr, { backgroundColor: k % 2 ? "#F8FAFC" : "#FFFFFF" }]}>
            <Text style={{ width: W.n, color: MUTED }}>{l.line_no}</Text>
            <View style={{ width: W.d, paddingRight: 4 }}><Text style={S.bold}>{l.description}</Text>{l.item_code && <Text style={{ color: MUTED, fontSize: 6.5 }}>{l.item_code}</Text>}</View>
            <Text style={{ width: W.u }}>{l.unit ?? ""}</Text>
            <Text style={[S.right, { width: W.c }]}>{qty(l.contract_qty)}</Text><Text style={[S.right, { width: W.p, color: MUTED }]}>{qty(l.prev_qty)}</Text>
            <Text style={[S.right, { width: W.t, fontWeight: 700 }]}>{qty(l.this_qty)}</Text><Text style={[S.right, { width: W.cu }]}>{qty(l.cum_qty)}</Text>
            <Text style={[S.right, { width: W.r }]}>{num(l.rate)}</Text><Text style={[S.right, { width: W.a, fontWeight: 700 }]}>{num(l.amount)}</Text>
          </View>
        ))}

        </View>

        {i.status === "paid" && <View style={{ alignSelf: "flex-end", borderWidth: 2.5, borderColor: "#16A34A", borderRadius: 4, paddingHorizontal: 12, paddingVertical: 2, marginTop: 10, marginBottom: 6 }}><Text style={{ fontSize: 20, fontWeight: 800, color: "#16A34A" }}>PAID</Text></View>}
        <View style={S.totals} wrap={false}>
          
          <View style={S.trow}><Text style={{ color: MUTED }}>Subtotal</Text><Text>{cur} {num(i.subtotal)}</Text></View>
          <View style={S.trow}><Text style={{ color: MUTED }}>VAT {i.vat_rate}%</Text><Text>{cur} {num(i.vat_amount)}</Text></View>
          <View style={[S.trow, { borderTopWidth: 1, borderTopColor: LINE, marginTop: 2, paddingTop: 3 }]}><Text style={S.bold}>Gross claimed</Text><Text style={S.bold}>{cur} {num(i.claimed_amount)}</Text></View>
          {d.certifiedState ? (
            <>
              <View style={[S.trow, { marginTop: 5 }]}><Text style={{ color: MUTED }}>Certified subtotal</Text><Text>{cur} {num(cert.subtotal)}</Text></View>
              <View style={S.trow}><Text style={{ color: MUTED }}>Certified VAT</Text><Text>{cur} {num(cert.vat)}</Text></View>
              <View style={S.trow}><Text style={S.bold}>Certified (gross)</Text><Text style={S.bold}>{cur} {num(i.certified_amount)}</Text></View>
              <View style={S.trow}><Text style={{ color: MUTED }}>Less retention ({i.retention_percent}%)</Text><Text>- {num(i.retention_amount)}</Text></View>
              <View style={S.trow}><Text style={{ color: MUTED }}>Less advance recovery ({i.advance_recovery_percent}%)</Text><Text>- {num(i.advance_recovery)}</Text></View>
              <View style={S.net}><Text style={{ color: "#fff", fontWeight: 800 }}>NET PAYABLE</Text><Text style={{ color: "#fff", fontWeight: 800 }}>{cur} {num(i.net_payable)}</Text></View>
            </>
          ) : <Text style={{ color: MUTED, marginTop: 5 }}>Awaiting certification.</Text>}
        </View>
        {d.certifiedState && <Text style={{ marginTop: 6, color: "#475569" }}>{amountInWords(i.net_payable, cur)}</Text>}

        {d.certifiedState && (
          <View style={{ marginTop: 12 }} wrap={false}>
            <Text style={S.h}>Certification remarks</Text>
            {remarks.length === 0 ? <Text style={{ color: MUTED }}>All lines certified as claimed{i.certified_amount < i.claimed_amount - 0.005 ? " (pro rata)" : ""}.</Text> : remarks.map((l) => (
              <Text key={l.id} style={{ marginBottom: 2 }}><Text style={S.bold}>Line {l.line_no}: </Text>{l.remarks} (claimed {num(l.amount)}, certified {num(l.certified_amount)})</Text>
            ))}
          </View>
        )}

        {d.trail.length > 0 && (
          <View style={{ marginTop: 12 }} wrap={false}>
            <Text style={S.h}>Approval trail</Text>
            <View style={[S.th, { backgroundColor: SOFT }]}>
              <Text style={[S.thText, { color: DARK, width: "14%" }]}>Document</Text><Text style={[S.thText, { color: DARK, width: "22%" }]}>Level</Text><Text style={[S.thText, { color: DARK, width: "20%" }]}>Approver</Text>
              <Text style={[S.thText, { color: DARK, width: "12%" }]}>Decision</Text><Text style={[S.thText, { color: DARK, width: "14%" }]}>Date</Text><Text style={[S.thText, { color: DARK, width: "18%" }]}>Comment</Text>
            </View>
            {d.trail.map((t, k) => (
              <View key={k} style={S.tr} wrap={false}>
                <Text style={{ width: "14%" }}>{t.document}</Text><Text style={{ width: "22%" }}>{t.level}</Text><Text style={{ width: "20%" }}>{t.approver}</Text>
                <Text style={{ width: "12%", textTransform: "capitalize" }}>{t.decision}</Text><Text style={{ width: "14%" }}>{date(t.date)}</Text><Text style={{ width: "18%", color: MUTED }}>{t.comment ?? ""}</Text>
              </View>
            ))}
          </View>
        )}

        {d.attachments.length > 0 && (
          <View style={{ marginTop: 12 }} wrap={false}>
            <Text style={S.h}>Attachments ({d.attachments.length})</Text>
            {d.attachments.map((a) => <Text key={a.id} style={{ marginBottom: 1.5 }}>{a.filename}  <Text style={{ color: MUTED }}>[{(a.category ?? "other").replace(/_/g, " ")}]</Text></Text>)}
          </View>
        )}

        <View style={{ flexDirection: "row", gap: 8, marginTop: 16 }} wrap={false}>
          {([["Submitted by", d.people.submittedBy, d.people.submittedAt], ["Reviewed by", d.people.reviewedBy, null], ["Certified by", d.people.certifiedBy, d.people.certifiedAt], ["Approved by", d.people.approvedBy, d.people.approvedAt]] as const).map(([k, who, when]) => (
            <View key={k} style={S.sig}>
              <Text style={S.label}>{k}</Text>
              <Text style={[S.bold, { marginTop: 18 }]}>{who ?? ""}</Text>
              <Text style={{ color: MUTED, fontSize: 7 }}>{when ? date(when) : ""}</Text>
            </View>
          ))}
        </View>

        </View>
      </Page>
    </Document>
  );
}
